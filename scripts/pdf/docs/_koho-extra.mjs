function apply(month, article) {
  if (!article || article.h === "人口" || String(article.h).includes("カレンダー")) return article;
  const key = `${month}:${article.h}`;
  const add = [...(EXTRA[key] || []), ...(MORE[key] ? [MORE[key]] : [])];
  if (!add.length) return article;
  const body = article.body || [];
  const toi = body.filter((b) => b && b.toi);
  const rest = body.filter((b) => !(b && b.toi));
  return { ...article, body: [...rest, ...add, ...toi] };
}

function mapList(month, list) {
  return (list || []).map((a) => apply(month, a));
}

export function withExtra(month, sheet) {
  return {
    ...sheet,
    photo: undefined,
    articles: mapList(month, sheet.articles),
    side: sheet.side ? apply(month, sheet.side) : undefined,
    below: sheet.below ? apply(month, sheet.below) : undefined,
    moreRight: mapList(month, sheet.moreRight),
    moreLeft: mapList(month, sheet.moreLeft),
    two: sheet.two ? sheet.two.map((col) => mapList(month, col)) : undefined,
  };
}
