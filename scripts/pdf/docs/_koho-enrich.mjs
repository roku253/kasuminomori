function applyBefore(month, article) {
  const pack = PACK[`${month}:${article.h}`];
  if (!pack?.before) return article;
  const toi = (article.body || []).filter((b) => b && b.toi);
  const rest = (article.body || []).filter((b) => !(b && b.toi));
  return { ...article, body: [...rest, ...pack.before, ...toi] };
}

export function enrichSheet(month, sheet) {
  if (sheet.two) {
    const two = sheet.two.map((col) => col.map((a) => applyBefore(month, a)));
    const pack = PACK[`${month}:${sheet.two[0][0].h}`] || {};
    if (pack.moreLeft) two[0] = [...two[0], ...pack.moreLeft];
    if (pack.moreRight) two[1] = [...two[1], ...pack.moreRight];
    const h = sheet.two[0][0].h;
    const hasGomi = sheet.two.some((col) => col.some((a) => a.h === "ごみ"));
    const extra = BELOW[`${month}:${h}`];
    if (hasGomi && extra) two[0] = [...two[0], extra];
    return { ...sheet, two, below: hasGomi ? GOMI : pack.below || extra || null, side: null, moreRight: null };
  }
  const first = sheet.articles[0];
  const pack = PACK[`${month}:${first.h}`] || {};
  const skip = String(first.h).includes("カレンダー") || first.h === "人口";
  return {
    ...sheet,
    articles: [...sheet.articles.map((a) => applyBefore(month, a)), ...(!skip && pack.moreLeft ? pack.moreLeft : [])],
    side: !skip && pack.side ? pack.side : null,
    moreRight: !skip
      ? [...(pack.moreRight || []), ...(first.h === "まちの話題" ? [SHOPS] : []), ...(String(first.h).includes("講座") ? [LECTURE] : [])]
      : null,
    below: pack.below || BELOW[`${month}:${first.h}`] || null,
  };
}
